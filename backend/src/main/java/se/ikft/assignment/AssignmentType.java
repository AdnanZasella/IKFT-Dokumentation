package se.ikft.assignment;

/**
 * Typ av dokumenteraruppdrag.
 */
public enum AssignmentType {

	/** Den ordinarie dokumenteraren. Gäller som längst till och med 31 december samma år. */
	ORDINARY,

	/** Ett tillfälligt uppdrag, t.ex. vid sjukdom eller semester, med ett bestämt slutdatum. */
	TEMPORARY

}
